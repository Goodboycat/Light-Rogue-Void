// Build bi-directional lookup mapping from Spanish back to English
const esToEnMap: Record<string, string> = {};

Object.entries(translations).forEach(([key, val]) => {
  if (val.es) {
    esToEnMap[val.es] = val.en || key;
  }
});

export const t = (text: string, lang: 'en' | 'es' = 'en'): string => {
  if (!text) return text;

  if (lang === 'en') {
    if (translations[text]?.en) {
      return translations[text].en;
    }
    if (esToEnMap[text]) {
      return esToEnMap[text];
    }
    return text;
  } else {
    if (translations[text]?.es) {
      return translations[text].es;
    }
    return text;
  }
};

export const translate = t;
