// Generates docs/STORY.md from data/story.ts (+ cinematics). Run: npm run story
import { execSync } from 'node:child_process';
import { writeFileSync, mkdirSync } from 'node:fs';
const js = execSync(`npx tsx -e "
import { STORY, STORY_BEAT_WAVES, WATCHER_WHISPERS, STORY_VOICE_COLOR } from './data/story.ts';
import { CHAPTERS, WAVES_PER_CHAPTER } from './components/game/Constants.ts';
import { OUTRO_SCRIPT } from './data/cinematics.ts';
console.log(JSON.stringify({ STORY, STORY_BEAT_WAVES, WATCHER_WHISPERS, STORY_VOICE_COLOR, CHAPTERS, WAVES_PER_CHAPTER, OUTRO_SCRIPT }));
"`, { encoding: 'utf8' });
const d = JSON.parse(js.trim().split('\n').pop());
const esc = s => s.replace(/\|/g, '\\|');
let out = `# LIGHT — Story script (3B)\n\nGenerated by \`npm run story\` (\`tools/dump-story.mjs\`) from \`data/story.ts\`. Do not edit by hand.\n\n`;
out += `## Voices\n| Voice | Colour | Who |\n|---|---|---|\n| LIGHT | \`${d.STORY_VOICE_COLOR.LIGHT}\` | you — hope, short sentences |\n| DARKNESS | \`${d.STORY_VOICE_COLOR.DARKNESS}\` | the void — mocking, cold |\n| WATCHER | \`${d.STORY_VOICE_COLOR.WATCHER}\` | a third voice, only at chapter seams (wave x9) and the ending |\n\n`;
out += `## Triggers\n- **opener** — wave x${d.STORY_BEAT_WAVES.opener} of the chapter (chapter wave 1), non-pausing caption (\`StoryCaption\`).\n- **mid** — chapter wave ${d.STORY_BEAT_WAVES.mid}, caption.\n- **preBoss** — chapter wave ${d.STORY_BEAT_WAVES.preBoss}, caption; the only in-run WATCHER slot.\n- **bossIntro / bossOutro** — pausing cinematic (\`CinematicOverlay\`) around the chapter boss (\`data/bossCinematics.ts\` holds the per-boss visual script; these are the story lines).\n- Chapter title card (\`ChapterCard\`) shows the chapter name + palette wash for 2 s on chapter entry.\n\n`;
let n = 0;
for (const ch of d.STORY) {
  const c = d.CHAPTERS[ch.chapter - 1];
  const w0 = (ch.chapter - 1) * d.WAVES_PER_CHAPTER;
  out += `## Chapter ${ch.chapter} — ${c.name} (waves ${w0 + 1}–${w0 + d.WAVES_PER_CHAPTER}, boss ${c.bossId})\n\n| Trigger | Wave | Voice | Line |\n|---|---|---|---|\n`;
  for (const [beat, wave] of [['opener', w0 + d.STORY_BEAT_WAVES.opener], ['mid', w0 + d.STORY_BEAT_WAVES.mid], ['preBoss', w0 + d.STORY_BEAT_WAVES.preBoss], ['bossIntro', c.bossWave], ['bossOutro', c.bossWave]]) {
    for (const l of ch[beat]) { out += `| ${beat} | ${wave} | ${l.voice} | ${esc(l.text)} |\n`; n++; }
  }
  out += '\n';
}
out += `## Ending — Seam of the Void (\`WinGame\`, after wave ${d.CHAPTERS.length * d.WAVES_PER_CHAPTER})\n\n### Outro cinematic (\`data/cinematics.ts\` OUTRO_SCRIPT)\n| Voice | Line |\n|---|---|\n`;
for (const l of d.OUTRO_SCRIPT) if (l.text) out += `| ${l.speaker} | ${esc(l.text)} |\n`;
out += `\n### WATCHER whispers (crawl in from the edges during the outro, random order)\n`;
for (const w of d.WATCHER_WHISPERS) out += `- *${w}*\n`;
out += `\n---\n${n} chapter lines · ${d.WATCHER_WHISPERS.length} whispers · every line ≤ 90 chars (checked by the 3B chat).\n`;
mkdirSync('../docs', { recursive: true });
writeFileSync('../docs/STORY.md', out);
console.log(`docs/STORY.md: ${n} lines`);
